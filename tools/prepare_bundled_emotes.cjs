// Prepare source assets only; this does not build, stage, install or publish a mod.
// Usage: node tools/prepare_bundled_emotes.cjs <folder containing the four originals>
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const sharp = require(process.env.LT_SHARP_MODULE || 'C:/Users/j9010/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
const root = path.resolve(__dirname, '..');
const digest = b => crypto.createHash('sha256').update(b).digest('hex');
const definitions = [
  ['Bomber_Nice.png', 'Bomber Nice', 'emote_bomber_nice', ['Bomber_Nice_0.2.png']],
  ['Clown_Son.png', 'Clown Son', 'emote_clown_son', ['Clown_Son_0.2.png']],
  ['Ghost_Wajaja.png', 'Ghost Wajaja', 'emote_ghost_wajaja'],
  ['Monk_NoKills.png', 'Monk No Kills', 'emote_monk_no_kills'],
];

// Same visible-bounds fit and premultiplied bilinear filter as emote_library::normalize.
// PNG encoders may produce different bytes; their decoded RGBA pixels match.
function normalize(data, w, h) {
  let x0=w, y0=h, x1=0, y1=0;
  for(let y=0;y<h;y++) for(let x=0;x<w;x++) if(data[(y*w+x)*4+3]) {
    x0=Math.min(x0,x); y0=Math.min(y0,y); x1=Math.max(x1,x+1); y1=Math.max(y1,y+1);
  }
  if(x0>=x1 || y0>=y1) throw Error('Image is fully transparent');
  const cw=x1-x0, ch=y1-y0, scale=224/Math.max(cw,ch);
  const dw=Math.max(1,Math.round(cw*scale)), dh=Math.max(1,Math.round(ch*scale));
  const ox=Math.floor((256-dw)/2), oy=Math.floor((256-dh)/2), out=Buffer.alloc(256*256*4);
  for(let y=0;y<dh;y++) for(let x=0;x<dw;x++) {
    const sx=Math.max(0,Math.min(cw-1,(x+.5)*cw/dw-.5));
    const sy=Math.max(0,Math.min(ch-1,(y+.5)*ch/dh-.5));
    const ix=Math.floor(sx), iy=Math.floor(sy), fx=sx-ix, fy=sy-iy, color=[0,0,0,0];
    for(const [px,py,weight] of [
      [ix,iy,(1-fx)*(1-fy)], [Math.min(ix+1,cw-1),iy,fx*(1-fy)],
      [ix,Math.min(iy+1,ch-1),(1-fx)*fy], [Math.min(ix+1,cw-1),Math.min(iy+1,ch-1),fx*fy],
    ]) {
      const at=((y0+py)*w+x0+px)*4, alpha=data[at+3]/255;
      color[3]+=alpha*weight;
      for(let c=0;c<3;c++) color[c]+=data[at+c]*alpha*weight;
    }
    const at=((oy+y)*256+ox+x)*4;
    if(color[3]>0) {
      for(let c=0;c<3;c++) out[at+c]=Math.max(0,Math.min(255,Math.round(color[c]/color[3])));
      out[at+3]=Math.round(color[3]*255);
    }
  }
  return out;
}

(async()=>{
  const input=process.argv[2];
  if(!input) throw Error('Pass the folder containing the four original PNGs');
  const files={}, entries=[], prepared=[];
  // Validate all four before changing any source asset.
  for(const [filename,label,glyph,oldNames=[]] of definitions) {
    const original=path.join(input,filename), stat=fs.lstatSync(original);
    if(!stat.isFile() || stat.isSymbolicLink() || stat.size>1048576) throw Error('Invalid source: '+filename);
    const bytes=fs.readFileSync(original), meta=await sharp(bytes).metadata();
    // Curated source art can be larger than the runtime import limit; only 256px outputs ship.
    if(meta.format!=='png' || meta.width>1024 || meta.height>1024 || (meta.pages||1)>1) throw Error('Unsupported image: '+filename);
    const {data,info}=await sharp(bytes).toColourspace('srgb').ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const pixels=normalize(data,info.width,info.height);
    const output=await sharp(pixels,{raw:{width:256,height:256,channels:4}}).png().toBuffer();
    const file=`ui/bundled/${glyph}.png`;
    entries.push({filename,label,glyph:`bundled/${glyph}`,id:`custom:${digest(Buffer.from(filename.toLowerCase()))}`,
      aliases:oldNames.map(n=>`custom:${digest(Buffer.from(n.toLowerCase()))}`),source_sha256:digest(bytes)});
    files[file]=digest(output); prepared.push([file,output]);
  }
  for(const [file,bytes] of prepared) {
    fs.mkdirSync(path.dirname(path.join(root,'probe',file)),{recursive:true});
    fs.writeFileSync(path.join(root,'probe',file),bytes);
  }
  const rust='// Generated by tools/prepare_bundled_emotes.cjs; metadata only, no embedded images.\nuse super::Bundled;\n\npub(super) const ENTRIES: &[Bundled] = &[\n'+entries.map(e=>
    '    Bundled {\n'+Object.entries(e).map(([k,v])=>`        ${k}: ${k==='aliases'?'&':''}${JSON.stringify(v)},`).join('\n')+'\n    },').join('\n')+'\n];\n';
  const catalogue=path.join(root,'probe/src/emote_library/bundled.rs');
  fs.mkdirSync(path.dirname(catalogue),{recursive:true}); fs.writeFileSync(catalogue,rust);
  const record={source:'tools/prepare_bundled_emotes.cjs',source_sha256:digest(fs.readFileSync(__filename)),
    catalogue:'probe/src/emote_library/bundled.rs',catalogue_sha256:digest(Buffer.from(rust)),
    art:'Four user-provided emotes; originals remain outside the repository and are not modified.',
    canvas:[256,256],visible_longest_side:224,entries,files};
  fs.writeFileSync(path.join(root,'tools/records/bundled-emotes.json'),JSON.stringify(record,null,2)+'\n');
  const manifest=path.join(root,'tools/records/ui-graphics.json'), m=JSON.parse(fs.readFileSync(manifest));
  Object.assign(m.files,files); fs.writeFileSync(manifest,JSON.stringify(m,null,2)+'\n');
  console.log('Prepared four normalized source PNGs and Library metadata; no release build or package was created.');
})().catch(e=>{console.error(e);process.exitCode=1;});
